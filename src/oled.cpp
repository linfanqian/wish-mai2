// SSD1306 initialization command sequence (from lab 15-oled-display)
static const u8 s_InitSequence[] =
{
    0xAE,        // Display OFF
    0xA8, 0x3F,  // Multiplex ratio 63 (64 rows)
    0xD3, 0x00,  // Display offset 0
    0x40,        // Start line 0
    0xA1,        // Segment remap (col 127 → SEG0)
    0xC8,        // COM scan direction remapped
    0xDA, 0x12,  // COM pins: alternative, no remap (128×64)
    0x81, 0x7F,  // Contrast 127
    0xA4,        // Display from RAM
    0xA6,        // Normal (not inverted)
    0xD5, 0x80,  // Clock divide ratio / oscillator frequency
    0x8D, 0x14,  // Charge pump enable
    0x20, 0x00,  // Horizontal addressing mode
    0xAF,        // Display ON
};

COLED::COLED (CI2CMaster *pI2CMaster)
:    m_pI2CMaster (pI2CMaster)
{
    m_I2CBuffer[0] = 0x40;   // I2C control byte
    m_DisplayBuffer = m_I2CBuffer + 1;
    memset (m_DisplayBuffer, 0, DisplayBufferSize);
}

boolean COLED::Initialize (void)
{
    for (unsigned i = 0; i < sizeof s_InitSequence; i++)
        SendCommand (s_InitSequence[i]);

    Clear ();
    Show ();

    CLogger::Get ()->Write ("oled", LogNotice, "SSD1306 OLED initialized");

    return TRUE;
}

void COLED::Clear (void)
{
    memset (m_DisplayBuffer, 0, DisplayBufferSize);
}

void COLED::Show (void)
{
    m_pI2CMaster->Write (I2CAddress, m_I2CBuffer, I2CBufferSize);
}

void COLED::DrawPixel (unsigned nX, unsigned nY, boolean bOn)
{
    if (nX >= DisplayWidth || nY >= DisplayHeight)
        return;

    u8 *pByte = &m_DisplayBuffer[(nY / 8) * DisplayWidth + nX];

    if (bOn)
        *pByte |=  (1 << (nY & 7));
    else
        *pByte &= ~(1 << (nY & 7));
}

void COLED::DrawLine (unsigned nX0, unsigned nY0, unsigned nX1, unsigned nY1, boolean bOn)
{
    unsigned x = nX0, y = nY0;
    int dx = (nX1 > nX0) ? nX1 - nX0 : nX0 - nX1;
    int dy = (nY1 > nY0) ? nY1 - nY0 : nY0 - nY1;
    int sx = (nX0 < nX1) ? 1 : -1;
    int sy = (nY0 < nY1) ? 1 : -1;

    // Tracks how far the "ideal" line has drifted from the pixel grid
    // When it gets too large in one axis, the other axis steps to compensate
    int err = dx - dy;
    for (;;)
    {
        DrawPixel (x, y, bOn);

        if (x == nX1 && y == nY1) break;

        int e2 = err * 2;    // to avoid division
        if (e2 > -dy) { 
            err -= dy; 
            x += sx; 
        }
        if (e2 < dx) { 
            err += dx; 
            y += sy; 
        }
    }
}

void COLED::DrawFillRect (unsigned nX, unsigned nY, unsigned nW, unsigned nH, boolean bOn)
{
    for (unsigned y = nY; y < nY + nH; y++)
        DrawLine (nX, y, nX + nW - 1, y, bOn);
}

void COLED::DrawButton (unsigned nCX, unsigned nCY, boolean bPressed)
{
    unsigned nHalf = bPressed ? 5 : 2;
    DrawFillRect (nCX - nHalf, nCY - nHalf, nHalf * 2 + 1, nHalf * 2 + 1, TRUE);
}

// https://github.com/adafruit/Adafruit-GFX-Library/blob/ac6d7c3869a693d406f77b9bfcd486b0673169f0/Adafruit_GFX.cpp#L1249
void COLED::DrawChar (unsigned nX, unsigned nY, char c, unsigned nScale)
{
    if ((unsigned) c >= sizeof s_Font / sizeof *s_Font)
        return;
    
    if (nX >= DisplayWidth || nY >= DisplayHeight)
        return;

    for (unsigned col = 0; col < 5; col++)
    {
        u8 line = s_Font[(unsigned) c][col];
        for (unsigned row = 0; row < 8; row++, line >>= 1)
        {
            if (line & 1)
            {
                for (unsigned sy = 0; sy < nScale; sy++)
                    for (unsigned sx = 0; sx < nScale; sx++)
                        DrawPixel (nX + col * nScale + sx,
                                   nY + row * nScale + sy, TRUE);
            }
        }
    }
}

void COLED::DrawText (unsigned nX, unsigned nY, const char *pText,
                      unsigned nScale)
{
    unsigned nCharWidth = 6 * nScale;   // 5px char + 1px gap
    size_t nLen = strlen (pText);

    for (unsigned i = 0; i < nLen; i++)
        DrawChar (nX + nCharWidth * i, nY, pText[i], nScale);
}

void COLED::SendCommand (u8 cmd)
{
    u8 buf[2] = {0x00, cmd};
    m_pI2CMaster->Write (I2CAddress, buf, 2);
}
